"""Generates the TweakXL records for the Capri cyberdeck from the CET TweakDB dump.

The deck builds every quickhack in: it lists each max-tier program's quickhacks (all tiers,
in the program's own order, because the game de-duplicates by action name and keeps the last
one) and copies the programs' passives into its OnEquip. Re-run after a new dump:

    .venv/Scripts/python.exe tools/deck/gen_tweaks.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DUMP = ROOT / "research" / "tweakdb_dump.json"
OUT = ROOT / "src" / "tweaks" / "capri" / "capri.yaml"

BASE_DECK = "Items.AdvancedNetwatchNetdriverMKLegendaryPlusPlus"

PROGRAMS = [
    "PingLvl4PlusPlusProgram",
    "WhistleLvl4PlusPlusProgram",
    "MemoryWipeLvl4PlusPlusProgram",
    "BlindLvl4PlusPlusProgram",
    "WeaponMalfunctionLvl4PlusPlusProgram",
    "LocomotionMalfunctionLvl4PlusPlusProgram",
    "DisableCyberwareLvl4PlusPlusProgram",
    "CommsNoiseLvl4PlusPlusProgram",
    "CommsCallInLvl4PlusPlusProgram",
    "EMPOverloadLvl4PlusPlusProgram",
    "OverheatLvl4PlusPlusProgram",
    "ContagionLvl4PlusPlusProgram",
    "BrainMeltLvl4PlusPlusProgram",
    "MadnessLvl4PlusPlusProgram",
    "SuicideLvl4PlusPlusProgram",
    "GrenadeExplodeLvl4PlusPlusProgram",
    "SystemCollapseLvl4PlusPlusProgram",
    "BlackWallProgramLvl4",
]

# Replaced by Capri's own permanent version below.
SKIPPED_ACTIONS = {"QuickHack.MadnessSetFriendlyHack"}

OVERRIDE_HACK = "QuickHack.CapriOverrideHack"
OVERRIDE_EFFECT = "QuickHack.CapriOverrideEffect"

# Capri's own quickhacks: (record, actionName, base action, base UI for the icon, text key).
# They carry no vanilla effects; r6/scripts/capri runs them on completion by actionName.
# People hacks are added to every NPC's menu by script; Down Aircraft replaces an AV's
# (locked) car hacks.
OWN_HACKS = [
    ("QuickHack.CapriEMPHack", "CapriEMP", "QuickHack.PingLvl4PlusPlusHack", "Interactions.EMPOverloadHack", "EMP"),
    ("QuickHack.CapriBlackoutHack", "CapriBlackout", "QuickHack.PingLvl4PlusPlusHack", "Interactions.ToggleStateHack", "Blackout"),
    ("QuickHack.CapriAuraHack", "CapriAura", "QuickHack.PingLvl4PlusPlusHack", "Interactions.BlackwallHack", "Aura"),
    ("DeviceAction.CapriDownAircraftHack", "CapriDownAircraft", "DeviceAction.VehicleExplodeClassHack", "Interactions.VehicleExplodeClassHack", "DownAircraft"),
]


def own_hack_records():
    blocks = []
    for record, action_name, base, ui, key in OWN_HACKS:
        ui_record = f"Interactions.Capri{key}"
        blocks.append(f"""{ui_record}:
  $base: {ui}
  caption: LocKey#Capri-{key}-Name
  description: LocKey#Capri-{key}-Desc

{record}:
  $base: {base}
  actionName: {action_name}
  objectActionUI: {ui_record}
  priority: 10
  activationTime: []
  completionEffects: []
  startEffects: []
  targetActivePrereqs:
    - Prereqs.QuickHackUploadingPrereq
""")
    return "\n".join(blocks)


def unique(items):
    seen, out = set(), []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def yaml_list(items, indent):
    pad = " " * indent
    return "\n".join(f"{pad}- {item}" for item in items)


def main():
    dump = json.loads(DUMP.read_text(encoding="utf-8"))
    deck = dump["cyberdecks"][BASE_DECK]
    friendly = dump["quickhacks"]["QuickHack.MadnessSetFriendlyHack"]

    actions = list(deck["objectActions"])
    passives = list(deck["OnEquip"])
    for name in PROGRAMS:
        program = dump["programs"]["Items." + name]
        actions += [a for a in program["objectActions"]
                    if a.startswith("QuickHack.") and a not in SKIPPED_ACTIONS]
        passives += program["OnEquip"] + program["OnAttach"]
    actions.append(OVERRIDE_HACK)
    actions += [hack[0] for hack in OWN_HACKS]

    # Duplicates keep their LAST position so the highest tier stays last per action name.
    actions = list(reversed(unique(reversed(actions))))
    passives = unique(passives)

    completion = [OVERRIDE_EFFECT if e == "QuickHack.MadnessSetFriendlyHack_inline4" else e
                  for e in friendly["completionEffects"]]

    text = f"""# GENERATED by tools/deck/gen_tweaks.py from research/tweakdb_dump.json - do not edit by hand.

# Capri: Operating System cyberdeck. Every quickhack built in at max tier; cost, upload,
# cooldown, spread and targeting are handled by the redscript side (r6/scripts/capri).
Items.CapriCyberdeck:
  $base: {BASE_DECK}
  displayName: LocKey#Capri-Deck-Name
  localizedDescription: LocKey#Capri-Deck-Desc
  friendlyName: Capri
  buyPrice: []
  sellPrice: []
  objectActions:
{yaml_list(actions, 4)}
  OnEquip:
{yaml_list(passives, 4)}

# Sold only by Viktor Vektor, always in stock, free.
Vendors.CapriDeckStock:
  $type: VendorItem
  item: Items.CapriCyberdeck
  quantity:
    - Vendors.Always_Present
  generationPrereqs: []

Vendors.wat_lch_ripperdoc_01:
  itemStock:
    - !append-once Vendors.CapriDeckStock

# Override: the target joins V's side until it dies (vanilla SetFriendly with no end time;
# vanilla force-kills turned drones when the effect ends, so it must never end).
BaseStatusEffect.CapriOverride:
  $base: BaseStatusEffect.SetFriendly
  duration: BaseStats.InfiniteDuration

{OVERRIDE_EFFECT}:
  $base: QuickHack.MadnessSetFriendlyHack_inline4
  statusEffect: BaseStatusEffect.CapriOverride

{OVERRIDE_HACK}:
  $base: QuickHack.MadnessSetFriendlyHack
  actionName: CapriOverride
  priority: 10
  completionEffects:
{yaml_list(completion, 4)}

# --- Capri's own quickhacks ---

{own_hack_records()}"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(actions)} actions, {len(passives)} passives")


if __name__ == "__main__":
    main()
